    w("| 交法 | 要求 |")
    w("| --- | --- |")
    w("| A. 单色线稿 SVG（推荐） | `viewBox 0 0 24 24`，描边 2.2、圆端点，`currentColor`。代码把它印在组色的圆盘上，图形本身是白色 |")
    w("| B. 彩色 PNG | **186 × 186 px**，透明底，圆形构图，主体占 70 %。这时圆盘会改成浅色底，组色只留在边圈上 |")
