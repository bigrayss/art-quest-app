def icon_places():
    """每枚图标在 HTML 里出现在哪一屏。"""
    out, cur = {}, "（顶栏 / 全局）"
    for line in HTML.splitlines():
        m = re.search(r'<section[^>]*id="(view-[\w-]+)"', line)
        if m:
            cur = m.group(1)
        m2 = re.search(r'<div class="modal[^"]*"[^>]*id="([\w-]+)"', line)
        if m2:
            cur = "弹窗"
        for ic in re.findall(r'data-icon="(\w+)"', line):
            out.setdefault(ic, set()).add(VIEW.get(cur, cur))
    return out


def unused_icons(names):
    """定义了但一次都没被用到的图标——留着备用不是坏事，但清单里要说实话。"""
    block = re.search(r'const ICONS = \{(.*?)\n  \};', APP, re.S)
    body = APP[:block.start()] + APP[block.end():]
    return {n for n in names
            if not re.findall(r'"%s"' % n, body) and not re.findall(r'data-icon="%s"' % n, HTML)}


